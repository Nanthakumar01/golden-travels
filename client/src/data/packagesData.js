export function matchesSearchQuery(pkg, query) {
	if (!query) return false
	const q = query.toLowerCase().trim()
	if (!q) return false
	return (
		(pkg.title && pkg.title.toLowerCase().includes(q)) ||
		(pkg.shortTitle && pkg.shortTitle.toLowerCase().includes(q)) ||
		(pkg.region && pkg.region.toLowerCase().includes(q)) ||
		(pkg.destination && pkg.destination.toLowerCase().includes(q)) ||
		(pkg.cities && pkg.cities.toLowerCase().includes(q)) ||
		(pkg.type && pkg.type.toLowerCase().includes(q)) ||
		(pkg.tags && pkg.tags.some(tag => tag.toLowerCase().includes(q))) ||
		(pkg.about && pkg.about.toLowerCase().includes(q))
	)
}

export function getPackageBySlug(slug) {
	if (!slug) return packagesData[0]
	const s = String(slug).toLowerCase()
	return (
		packagesData.find(p => p.slug === s || String(p.id) === s) ||
		packagesData.find(p => p.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').includes(s)) ||
		packagesData[0]
	)
}
